#!/usr/bin/env node
// Compares the API paths the web app calls (apiRequest helper) with the routes
// the SQL-only server registers. Pure Node, no dependencies.
//
// Usage:
//   node scripts/verify-api-parity.mjs            report to stdout
//   node scripts/verify-api-parity.mjs --write    also write docs/API_PARITY_GAP.md
//   node scripts/verify-api-parity.mjs --strict   exit 1 when any web path has no server route
//
// This is a static, approximate check: it matches path shapes only, not HTTP
// methods or payloads, and cannot see paths built entirely at runtime.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist') continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full);
    else yield full;
  }
}

// Server routes: app.<method>('<path>', ...) in the server sources.
const routePattern = /\bapp\.(get|post|put|patch|delete)\(\s*['"`]([^'"`]+)['"`]/g;
const serverRoutes = [];
for (const file of walk(join(root, 'apps/server/src'))) {
  if (!/\.ts$/.test(file) || /\.test\.ts$/.test(file)) continue;
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(routePattern)) {
    const path = m[2].replace(/^\/api(?=\/|$)/, '');
    if (path && path !== '/health') serverRoutes.push({ method: m[1].toUpperCase(), path });
  }
}
const toRegex = (p) => new RegExp('^' + p.replace(/:[A-Za-z0-9_]+/g, '[^/]+') + '/?$');
const serverMatchers = serverRoutes.map((r) => toRegex(r.path));

// Web calls: apiRequest(<optional generics>)('/path' | `/path/${id}`).
const callPattern = /apiRequest(?:<[^()]*?>)?\(\s*([`'"])(\/(?:(?!\1)[^\\]|\\.)*?)\1/gs;
const calls = new Map();
for (const file of walk(join(root, 'apps/web/src'))) {
  if (!/\.tsx?$/.test(file)) continue;
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(callPattern)) {
    const path = m[2]
      .replace(/\$\{[^}]*\}/g, ':id')
      .replace(/[?$].*$/s, '')
      .replace(/\/+$/, '') || '/';
    const entry = calls.get(path) ?? { count: 0, files: new Set() };
    entry.count += 1;
    entry.files.add(relative(root, file));
    calls.set(path, entry);
  }
}

const served = [];
const missing = [];
for (const [path, info] of calls) {
  (serverMatchers.some((re) => re.test(path)) ? served : missing).push({ path, ...info });
}
const byPath = (a, b) => a.path.localeCompare(b.path);
served.sort(byPath);
missing.sort(byPath);

const group = (path) => path.split('/')[1] === 'metadata' ? `metadata/${path.split('/')[2] ?? ''}` : path.split('/')[1] ?? '';
const groups = new Map();
for (const m of missing) {
  const g = group(m.path);
  groups.set(g, [...(groups.get(g) ?? []), m]);
}

const lines = [];
lines.push('# API parity gap: web app vs SQL-only server', '');
lines.push('Generated by `node scripts/verify-api-parity.mjs --write`. Do not edit by hand; rerun the script.', '');
lines.push('This is a static path-shape comparison. It does not compare HTTP methods or payloads, so a path listed as served may still lack a method or field the web app needs.', '');
lines.push('| | Count |', '|---|---|');
lines.push(`| Server routes registered | ${serverRoutes.length} |`);
lines.push(`| Distinct web API paths | ${calls.size} |`);
lines.push(`| Web paths with a matching server route | ${served.length} |`);
lines.push(`| Web paths with **no** server route | ${missing.length} |`, '');
lines.push('## Web paths with no server route, by area', '');
for (const [g, items] of [...groups].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))) {
  lines.push(`### ${g} (${items.length})`, '');
  for (const it of items) lines.push(`- \`${it.path}\` — ${it.count} call${it.count > 1 ? 's' : ''} in ${[...it.files].map((f) => `\`${f.replace('apps/web/src/', '')}\``).join(', ')}`);
  lines.push('');
}
lines.push('## Web paths already served', '');
for (const it of served) lines.push(`- \`${it.path}\``);
lines.push('', '## Server routes', '');
for (const r of serverRoutes.sort((a, b) => a.path.localeCompare(b.path))) lines.push(`- \`${r.method} /api${r.path}\``);
lines.push('');
const report = lines.join('\n');

console.log(`Server routes: ${serverRoutes.length} | web API paths: ${calls.size} | served: ${served.length} | missing: ${missing.length}`);
for (const [g, items] of [...groups].sort((a, b) => b[1].length - a[1].length)) console.log(`  ${String(items.length).padStart(3)}  ${g}`);
if (args.has('--write')) {
  writeFileSync(join(root, 'docs/API_PARITY_GAP.md'), report);
  console.log('Wrote docs/API_PARITY_GAP.md');
}
if (args.has('--strict') && missing.length > 0) process.exit(1);
